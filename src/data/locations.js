export const CITY_ALIASES = {
  Barisal: 'Barishal',
  Bogora: 'Bogura',
  Chittagong: 'Chattogram',
  Comilla: 'Cumilla',
  Jessore: 'Jashore',
  Jhalokati: 'Jhalokathi',
  CoxsBazar: "Cox's Bazar",
  "Coxs Bazar": "Cox's Bazar"
};

export function normalizeCityName(city) {
  if (!city) return '';
  const trimmed = city.trim();
  if (CITY_ALIASES[trimmed]) return CITY_ALIASES[trimmed];
  const matched = CITIES.find((c) => c.toLowerCase() === trimmed.toLowerCase());
  return matched || trimmed;
}

export function getCitySearchVariants(city) {
  const normalized = normalizeCityName(city);
  const variants = new Set([normalized.toLowerCase()]);
  Object.entries(CITY_ALIASES).forEach(([alias, canonical]) => {
    if (canonical.toLowerCase() === normalized.toLowerCase()) {
      variants.add(alias.toLowerCase());
    }
  });
  return Array.from(variants);
}

export function getAreasForCity(city, extraArea = '') {
  const normalized = normalizeCityName(city);
  const list = LOCATIONS_BY_CITY[normalized] ? [...LOCATIONS_BY_CITY[normalized]] : [];
  if (extraArea && !list.some((a) => a.toLowerCase() === extraArea.toLowerCase())) {
    list.unshift(extraArea);
  }
  return list;
}

